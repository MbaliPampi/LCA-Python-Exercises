# Question 1: Using a for loop with a list
fruits = ["apple", "banana", "orange", "cherry", "watermelon"]
for fruit in fruits:
    print(fruit)

# Question 2: Using a while loop for countdown
count = 5
while count >= 1:
    print(count)
    count -= 1

# Question 3: Using a for loop with range 
for i in range(1, 11):
  print(i * i)

# Question 4: Using the random module import random
colours = ["gold", "silver", "pink", "white", "grey"]
for i in range(3):
    print(random.choice(colours))

      
